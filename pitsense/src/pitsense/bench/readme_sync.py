"""Regenerate the README's results section from ``reports/results.md`` (``pitsense results --readme``).

The README holds a block between ``<!-- results:begin -->`` and ``<!-- results:end -->``; everything in it is
replaced by the benchmark, call-score, decision-value, voice and audit sections of results.md (per-circuit and
other split tables stay in results.md). Run ``python -m pitsense.bench.readme_sync`` after ``pitsense results``.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

BEGIN, END = "<!-- results:begin -->", "<!-- results:end -->"
SECTIONS = ("benchmark", "calls", "decision", "voice", "audit")


def sections(md: str) -> dict[str, str]:
    parts = re.split(r"<!-- results:(\w+) -->\n", md)
    out = {parts[i]: parts[i + 1] for i in range(1, len(parts) - 1, 2)}
    if "audit" in out:
        out["audit"] = out["audit"].split("\n## Provenance")[0]
    if "calls" in out:  # the split tables stay in results.md
        out["calls"] = out["calls"].split("\nBy ")[0] + "\nSplits by weather, safety car, race phase and circuit: `reports/results.md`.\n"
    return out


def block(md: str) -> str:
    sec = sections(md)
    head = md.split("<!-- results:")[0].split("\n", 2)[-1].strip()
    body = [s.replace("\n## ", "\n### ").replace("## ", "### ", 1) for k in SECTIONS if (s := sec.get(k))]
    return "\n".join([BEGIN, "<!-- generated by `pitsense results --readme` from reports/results.md; do not edit by hand -->", "",
                      head, "", *body, END])


def sync(results_md: Path, readme: Path) -> None:
    text = readme.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{readme}: no {BEGIN} ... {END} block")
    pre, rest = text.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    readme.write_text(pre + block(results_md.read_text(encoding="utf-8")) + post, encoding="utf-8")


if __name__ == "__main__":
    sync(Path(sys.argv[1] if len(sys.argv) > 1 else "reports/results.md"), Path(sys.argv[2] if len(sys.argv) > 2 else "README.md"))
